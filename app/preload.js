const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('cockpit', {
  add: (o) => ipcRenderer.invoke('add', o),
  switchTo: (id) => ipcRenderer.invoke('switch', id),
  rename: (id, name) => ipcRenderer.invoke('rename', { id, name }),
  reorder: (ids) => ipcRenderer.invoke('reorder', ids),
  setEditing: (on) => ipcRenderer.invoke('setEditing', !!on),
  reload: (id) => ipcRenderer.invoke('reload', id),
  setInbox: (id, mode) => ipcRenderer.invoke('setInbox', { id, mode }),
  remove: (id) => ipcRenderer.invoke('remove', id),
  win: (a) => ipcRenderer.invoke('win', a),
  nav: (d) => ipcRenderer.invoke('nav', d),
  refreshUsage: () => ipcRenderer.invoke('refreshUsage'),
  openBilling: () => ipcRenderer.invoke('openBilling'),
  exportDiag: () => ipcRenderer.invoke('exportDiag'),
  home: () => ipcRenderer.invoke('home'),
  getState: () => ipcRenderer.invoke('getState'),
  installUpdate: () => ipcRenderer.invoke('installUpdate'),
  checkUpdate: () => ipcRenderer.invoke('checkUpdate'),
  version: () => ipcRenderer.invoke('version'),
  machine: () => ipcRenderer.invoke('machine'),
  copyText: (t) => ipcRenderer.invoke('copyText', t),
  joinKeyCopy: () => ipcRenderer.invoke('joinKeyCopy'),
  joinKeyReset: () => ipcRenderer.invoke('joinKeyReset'),
  mailPause: (on) => ipcRenderer.invoke('mailPause', on),
  mailRetry: (id) => ipcRenderer.invoke('mailRetry', id),
  mailClear: () => ipcRenderer.invoke('mailClear'),
  mailTeach: (id) => ipcRenderer.invoke('mailTeach', id),
  mailFiles: (id) => ipcRenderer.invoke('mailFiles', id),
  notes: () => ipcRenderer.invoke('notes'),
  openNotes: () => ipcRenderer.invoke('openNotes'),
  onNotes: (cb) => ipcRenderer.on('notes', (_e, s) => cb(s)),
  onOpenNotes: (cb) => ipcRenderer.on('openNotes', () => cb()),
  onUpdate: (cb) => ipcRenderer.on('update', (_e, s) => cb(s)),
  onToast: (cb) => ipcRenderer.on('toast', (_e, s) => cb(s)),
  onState: (cb) => ipcRenderer.on('state', (_e, s) => cb(s)),
});
